/**
 * i18n Manager
 */
class I18nManager {
  constructor() {
    this.currentLang = this.detectLanguage();
    this.listeners = [];
  }

  /** Detect language from localStorage or browser */
  detectLanguage() {
    const saved = localStorage.getItem('blankup_lang');
    if (saved && translations[saved]) return saved;
    const browserLang = navigator.language.slice(0, 2);
    return browserLang === 'vi' ? 'vi' : 'en';
  }

  /** Get translation by key. Params: {key: value} replaces {key} placeholders */
  t(key, params) {
    let text = translations[this.currentLang]?.[key] || translations['vi']?.[key] || key;
    if (params && typeof text === 'string') {
      for (const [name, value] of Object.entries(params)) {
        text = text.split(`{${name}}`).join(String(value ?? ''));
      }
    }
    return text;
  }

  /** Switch language */
  switchTo(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('blankup_lang', lang);
    this.updateDOM();
    this.listeners.forEach(fn => fn(lang));
  }

  /** Toggle between VI and EN */
  toggle() {
    this.switchTo(this.currentLang === 'vi' ? 'en' : 'vi');
  }

  /** Update all DOM elements with data-i18n attribute */
  updateDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.textContent = text;
      }
    });

    // Update data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });

    // Update data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.getAttribute('data-i18n-title'));
    });

    // Update html lang attribute
    document.documentElement.lang = this.currentLang;
    document.documentElement.setAttribute('data-lang', this.currentLang);

    // Update language toggle button
    const toggleBtns = document.querySelectorAll('.lang-toggle, .nav-lang');
    toggleBtns.forEach(btn => {
      const activeLang = this.currentLang;
      btn.querySelectorAll('[data-lang]').forEach(span => {
        span.classList.toggle('active', span.getAttribute('data-lang') === activeLang);
        span.setAttribute('aria-pressed', String(span.getAttribute('data-lang') === activeLang));
      });
    });
  }

  /** Register language change listener */
  onChange(fn) {
    this.listeners.push(fn);
  }

  /** Initialize - call after DOM loaded */
  init() {
    this.updateDOM();
    // Bind language toggle buttons (idempotent — safe to call multiple times)
    const containers = [...document.querySelectorAll('.lang-toggle, .nav-lang, #langToggle')]
      .filter((el, i, arr) => arr.indexOf(el) === i);
    containers.forEach(btn => {
      if (btn.dataset.i18nBound === '1') return;
      btn.dataset.i18nBound = '1';
      btn.addEventListener('click', (e) => {
        const target = e.target.closest('[data-lang]');
        if (target) {
          this.switchTo(target.getAttribute('data-lang'));
        }
      });
    });
  }
}

